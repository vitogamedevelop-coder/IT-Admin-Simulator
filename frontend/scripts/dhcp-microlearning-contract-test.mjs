const store = new Map();
globalThis.localStorage = {
  getItem: (k) => store.get(k) ?? null,
  setItem: (k, v) => store.set(k, String(v)),
  removeItem: (k) => store.delete(k),
  clear: () => store.clear(),
};
globalThis.window = { dispatchEvent: () => {}, addEventListener: () => {}, removeEventListener: () => {} };

import assert from 'node:assert/strict';
import { buildCiscoDhcpLesson, CISCO_DHCP_TOPIC_KEY } from '../src/lib/academyLessons/ciscoDhcp.js';
import { selectDirectTheoryExercises } from '../src/lib/lessonExerciseSelector.js';

const EVIDENCE_TYPES = new Set(['viewed', 'recognized', 'understood', 'recalled', 'applied', 'diagnosed', 'transferred']);

const lesson = buildCiscoDhcpLesson();

assert.equal(lesson.title, 'DHCP Relay', 'title');
assert.ok(lesson.explanations.length >= 9, 'has enough micro-explanation sections');
assert.ok(lesson.exercises.length >= 5, 'has enough exercises');
assert.equal(lesson.quiz.length, 5, 'quiz has 5 items');
assert.ok(lesson.cliTasks.length >= 4, 'has cli tasks');

const sectionIds = new Set();
const exerciseIds = new Set();

lesson.explanations.forEach((ex) => {
  assert.ok(ex.id, 'explanation has id');
  assert.ok(ex.title, 'explanation has title');
  assert.ok(Array.isArray(ex.blocks) && ex.blocks.length > 0, 'explanation has blocks');
  assert.ok(!sectionIds.has(ex.id), 'no duplicate explanation id');
  sectionIds.add(ex.id);
  ex.blocks.forEach((b) => {
    if (b.type === 'question') {
      assert.ok(b.question, 'question text exists');
      assert.ok(Array.isArray(b.options) && b.options.length > 1, 'question has options');
      assert.ok(b.correct >= 0 && b.correct < b.options.length, 'question has valid correct');
      if (b.evidenceType) assert.ok(EVIDENCE_TYPES.has(b.evidenceType), `inline evidence type valid: ${b.evidenceType}`);
    }
  });
});

lesson.exercises.forEach((ex) => {
  assert.ok(ex.id, 'exercise has id');
  assert.ok(!exerciseIds.has(ex.id), 'no duplicate exercise id');
  exerciseIds.add(ex.id);
  assert.ok(ex.evidenceType, `exercise ${ex.id} has evidenceType`);
  assert.ok(EVIDENCE_TYPES.has(ex.evidenceType), `exercise evidenceType valid: ${ex.evidenceType}`);
  assert.ok(Array.isArray(ex.relatedKnowledgeIds) && ex.relatedKnowledgeIds.length > 0, `exercise ${ex.id} has facets`);
});

lesson.quiz.forEach((q, i) => {
  assert.ok(q.question, `quiz ${i} has question`);
  assert.ok(q.evidenceType, `quiz ${i} has evidenceType`);
  assert.ok(Array.isArray(q.relatedKnowledgeIds) && q.relatedKnowledgeIds.length > 0, `quiz ${i} has facets`);
});

['nexus-intro', 'mental-model', 'recognize', 'understand-placement', 'scenarios', 'recall-command', 'apply-multi-vlan', 'diagnose-apiipa', 'verify', 'transfer', 'summary'].forEach((sid) => {
  assert.ok(sectionIds.has(sid), `section ${sid} exists`);
});

['recognized', 'understood', 'recalled', 'applied', 'diagnosed', 'transferred'].forEach((t) => {
  const found = lesson.exercises.some((ex) => ex.evidenceType === t) || lesson.quiz.some((q) => q.evidenceType === t);
  assert.ok(found, `evidence type ${t} is generated by at least one exercise/quiz`);
});

const direct = selectDirectTheoryExercises(lesson.exercises, CISCO_DHCP_TOPIC_KEY);
assert.ok(direct.length >= 3 && direct.length <= 8, 'direct theory selection is a compact subset');

console.log('DHCP micro-learning contract OK');
